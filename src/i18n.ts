export const messages: Record<string, Record<Key, string>> = { en, es }

export const languages = [
  ['en', 'English'],
  ['es', 'Español'],
] as const

const storageKey = 'happyx.lang'

// The saved choice if we still have that language; otherwise the first browser language we have
// (es-ES and ca, es both give es); English if none.
export function pickLanguage(saved: string | null, browser: readonly string[] = []): string {
  if (saved && messages[saved]) return saved
  for (const tag of browser) {
    const base = tag.toLowerCase().split('-')[0]
    if (messages[base]) return base
  }
  return 'en'
}

const browserLanguages = (): readonly string[] =>
  typeof navigator === 'undefined' ? [] : navigator.languages?.length ? navigator.languages : navigator.language ? [navigator.language] : []

function savedLanguage(): string | null {
  try {
    return localStorage.getItem(storageKey)
  } catch {
    return null
  }
}

export const lang = pickLanguage(typeof localStorage === 'undefined' ? null : savedLanguage(), browserLanguages())

// Every string is read at render time, so a reload is the simplest way to switch.
export function setLanguage(code: string) {
  try {
    localStorage.setItem(storageKey, code)
  } catch {
    // Private mode: the choice lasts until the reload below, which is as good as it gets.
  }
  location.reload()
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = messages[lang][key] ?? en[key]
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

export const moodEmojis = ['😞', '😕', '😐', '🙂', '🤩'] as const

// Averages are shown with one decimal, so the face follows that shown value: 3,46 and 3,54 both read
// «3,5» and both get 🙂.
const moodLevel = (mood: number) => Math.min(5, Math.max(1, Math.round(Math.round(mood * 10) / 10)))

export const moodEmoji = (mood: number) => moodEmojis[moodLevel(mood) - 1]

export const moodLabel = (mood: number) => t(`mood.${moodLevel(mood)}` as Key)

export function formatDay(day: string, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short' }): string {
  return new Intl.DateTimeFormat(lang, { ...opts, timeZone: 'UTC' }).format(new Date(`${day}T00:00:00Z`))
}

export const formatNumber = (n: number, digits = 0) =>
  new Intl.NumberFormat(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(n)

// «2–31 oct 2026», «29 sept – 5 oct 2026»: two dates written once, as the language joins them.
export function formatRange(from: string, to: string, year = true): string {
  const f = new Intl.DateTimeFormat(lang, { day: 'numeric', month: 'short', ...(year ? { year: 'numeric' } : {}), timeZone: 'UTC' })
  const d = (day: string) => new Date(`${day}T00:00:00Z`)
  return from === to ? f.format(d(from)) : f.formatRange(d(from), d(to))
}

// «los lunes», «Mondays»: a weekday in plural, as in «Mondays are the lowest day».
export function weekdayPlural(day: string): string {
  const name = formatDay(day, { weekday: 'long' })
  if (lang === 'es') return name.endsWith('s') ? name : `${name}s`
  return `${name}s`
}
